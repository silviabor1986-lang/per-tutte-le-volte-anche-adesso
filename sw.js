self.addEventListener('activate', function (ev) {
  ev.waitUntil(caches.keys().then(function (nomi) {
    return Promise.all(nomi.filter(function (n) {
      return n.indexOf('ptlv-app-') === 0 && n !== VERSIONE;
    }).map(function (n) { return caches.delete(n); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('fetch', function (ev) {
  var rq = ev.request;
  if (rq.method !== 'GET') return;
  var url = new URL(rq.url);
  if (url.origin !== self.location.origin) return;
  if (rq.headers.has('range')) return;
  ev.respondWith(rispondi(rq, url));
});

